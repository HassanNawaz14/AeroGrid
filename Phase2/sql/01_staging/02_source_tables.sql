-- WP-04 source-shaped staging tables for ADS-B, UAS, weather, and FAA sources.
-- Preserve source record identity and enough context to reproduce transformations.
-- Reject reasons are stored in stg_reject and/or the row-level reject_reason field.

CREATE TABLE IF NOT EXISTS project_staging.stg_adsb_position (
    staging_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id          BIGINT       NOT NULL,
    source_manifest_id  BIGINT,
    source_system       VARCHAR(32)  NOT NULL DEFAULT 'TARTAN',
    source_record_id    VARCHAR(160) NOT NULL,
    source_row_number   INTEGER,
    event_ts            TIMESTAMPTZ  NOT NULL,
    icao24              VARCHAR(16),
    callsign            VARCHAR(32),
    latitude            DOUBLE PRECISION,
    longitude           DOUBLE PRECISION,
    altitude_ft         DOUBLE PRECISION,
    altitude_source     VARCHAR(32),
    ground_speed_kts    DOUBLE PRECISION,
    heading_deg         DOUBLE PRECISION,
    vertical_rate_fps   DOUBLE PRECISION,
    on_ground           BOOLEAN,
    raw_file            TEXT,
    source_quality_flag VARCHAR(32),
    reject_reason       VARCHAR(64),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_stg_adsb_source_record UNIQUE (source_system, source_record_id)
);

CREATE INDEX IF NOT EXISTS ix_stg_adsb_event ON project_staging.stg_adsb_position (event_ts);
CREATE INDEX IF NOT EXISTS ix_stg_adsb_icao24 ON project_staging.stg_adsb_position (icao24);

CREATE TABLE IF NOT EXISTS project_staging.stg_uas_position (
    staging_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id          BIGINT       NOT NULL,
    source_manifest_id  BIGINT,
    source_system       VARCHAR(32)  NOT NULL,
    source_record_id    VARCHAR(160) NOT NULL,
    source_row_number   INTEGER,
    event_ts            TIMESTAMPTZ  NOT NULL,
    vehicle_serial      VARCHAR(128),
    flight_id           TEXT,
    latitude            DOUBLE PRECISION,
    longitude           DOUBLE PRECISION,
    altitude_msl_ft     DOUBLE PRECISION,
    altitude_agl_ft     DOUBLE PRECISION,
    ground_speed_kts    DOUBLE PRECISION,
    vertical_speed_fps  DOUBLE PRECISION,
    flight_state        VARCHAR(32),
    is_on_ground        BOOLEAN,
    is_motor_on         BOOLEAN,
    is_gps_used         BOOLEAN,
    home_latitude       DOUBLE PRECISION,
    home_longitude      DOUBLE PRECISION,
    home_altitude_ft    DOUBLE PRECISION,
    source_speed_value  DOUBLE PRECISION,
    source_speed_unit   VARCHAR(16),
    altitude_value      DOUBLE PRECISION,
    altitude_unit       VARCHAR(16),
    altitude_datum      VARCHAR(16),
    speed_value         DOUBLE PRECISION,
    speed_unit          VARCHAR(16),
    heading_deg         DOUBLE PRECISION,
    raw_file            TEXT,
    reject_reason       VARCHAR(64),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_stg_uas_source_record UNIQUE (source_system, source_record_id)
);

CREATE INDEX IF NOT EXISTS ix_stg_uas_event ON project_staging.stg_uas_position (event_ts);
CREATE INDEX IF NOT EXISTS ix_stg_uas_serial ON project_staging.stg_uas_position (vehicle_serial);

CREATE TABLE IF NOT EXISTS project_staging.stg_weather_metar (
    staging_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id          BIGINT       NOT NULL,
    source_manifest_id  BIGINT,
    source_system       VARCHAR(16)  NOT NULL,
    source_record_id    VARCHAR(160) NOT NULL,
    source_row_number   INTEGER,
    station_icao        VARCHAR(8)   NOT NULL,
    observation_ts      TIMESTAMPTZ  NOT NULL,
    report_type         VARCHAR(16),
    raw_text            TEXT,
    flight_category     VARCHAR(8),
    temperature_c       DOUBLE PRECISION,
    dewpoint_c          DOUBLE PRECISION,
    wind_speed_kts      DOUBLE PRECISION,
    wind_gust_kts       DOUBLE PRECISION,
    wind_direction_deg  SMALLINT,
    visibility_sm       DOUBLE PRECISION,
    cloud_ceiling_ft    INTEGER,
    altimeter_inhg      DOUBLE PRECISION,
    station_lat         DOUBLE PRECISION,
    station_lon         DOUBLE PRECISION,
    station_elevation_m DOUBLE PRECISION,
    reject_reason       VARCHAR(64),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_stg_weather_station_obs UNIQUE (station_icao, observation_ts, source_system)
);

CREATE INDEX IF NOT EXISTS ix_stg_weather_obs ON project_staging.stg_weather_metar (observation_ts);

CREATE TABLE IF NOT EXISTS project_staging.stg_airspace_zone (
    staging_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id          BIGINT       NOT NULL,
    source_manifest_id  BIGINT,
    source_system       VARCHAR(32)  NOT NULL,
    source_record_id    VARCHAR(160) NOT NULL,
    source_object_id    VARCHAR(160),
    source_row_number   INTEGER,
    service_name        VARCHAR(64),
    restriction_id      VARCHAR(64),
    zone_name           TEXT,
    airport_icao        VARCHAR(8),
    restriction_type    VARCHAR(48),
    lower_limit_ft      DOUBLE PRECISION,
    upper_limit_ft      DOUBLE PRECISION,
    effective_start_ts  TIMESTAMPTZ,
    effective_end_ts    TIMESTAMPTZ,
    is_static           BOOLEAN,
    geometry_wkt        TEXT,
    bbox_min_lat        DOUBLE PRECISION,
    bbox_min_lon        DOUBLE PRECISION,
    bbox_max_lat        DOUBLE PRECISION,
    bbox_max_lon        DOUBLE PRECISION,
    source_url          TEXT,
    raw_attributes      JSONB,
    reject_reason       VARCHAR(64),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_stg_airspace_source_record UNIQUE (source_system, source_record_id)
);

CREATE INDEX IF NOT EXISTS ix_stg_airspace_type ON project_staging.stg_airspace_zone (restriction_type);

CREATE TABLE IF NOT EXISTS project_staging.stg_restriction_snapshot (
    staging_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id          BIGINT       NOT NULL,
    snapshot_ts         TIMESTAMPTZ  NOT NULL,
    source_system       VARCHAR(32)  NOT NULL,
    source_object_id    VARCHAR(160) NOT NULL,
    restriction_id      VARCHAR(64),
    is_active           BOOLEAN,
    effective_start_ts  TIMESTAMPTZ,
    effective_end_ts    TIMESTAMPTZ,
    raw_json            JSONB,
    reject_reason       VARCHAR(64),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_stg_restriction_snapshot UNIQUE (source_system, source_object_id, snapshot_ts)
);

