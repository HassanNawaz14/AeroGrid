-- WP-04 staging DDL: source manifest, run log, rejects, and DQ result tables.
-- Canonical contract: data/data_dictionary.md and Phase2/docs/05_etl_pipeline.md.
-- Idempotent DDL; no destructive statements.

CREATE TABLE IF NOT EXISTS project_staging.source_manifest (
    source_manifest_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name         VARCHAR(64)  NOT NULL,
    source_url          TEXT         NOT NULL,
    license_name        VARCHAR(64)  NOT NULL,
    attribution         TEXT         NOT NULL,
    fetched_at          TIMESTAMPTZ  NOT NULL,
    file_name           TEXT         NOT NULL,
    byte_size           BIGINT       NOT NULL CHECK (byte_size >= 0),
    sha256              CHAR(64)     NOT NULL,
    object_key          TEXT,
    content_type        VARCHAR(64),
    source_version      VARCHAR(64),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_source_manifest_name_sha256 UNIQUE (source_name, sha256)
);

CREATE TABLE IF NOT EXISTS project_staging.etl_run_log (
    etl_run_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_mode              VARCHAR(16)  NOT NULL,
    started_at            TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    finished_at           TIMESTAMPTZ,
    status                VARCHAR(16)  NOT NULL DEFAULT 'RUNNING',
    code_version          VARCHAR(64),
    rows_read             BIGINT       NOT NULL DEFAULT 0 CHECK (rows_read >= 0),
    rows_accepted         BIGINT       NOT NULL DEFAULT 0 CHECK (rows_accepted >= 0),
    rows_rejected         BIGINT       NOT NULL DEFAULT 0 CHECK (rows_rejected >= 0),
    rows_duplicate        BIGINT       NOT NULL DEFAULT 0 CHECK (rows_duplicate >= 0),
    facts_inserted        BIGINT       NOT NULL DEFAULT 0 CHECK (facts_inserted >= 0),
    critical_dq_failures  INTEGER      NOT NULL DEFAULT 0 CHECK (critical_dq_failures >= 0),
    failure_reason        TEXT,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_etl_run_log_status
        CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED', 'PARTIAL')),
    CONSTRAINT ck_etl_run_log_counts
        CHECK (rows_read = rows_accepted + rows_rejected + rows_duplicate)
);

CREATE TABLE IF NOT EXISTS project_staging.stg_reject (
    reject_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id        BIGINT       NOT NULL,
    source_system     VARCHAR(32)  NOT NULL,
    source_record_id  VARCHAR(160),
    reason_code       VARCHAR(64)  NOT NULL,
    reason_detail     TEXT,
    raw_payload       TEXT,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_stg_reject_run ON project_staging.stg_reject (etl_run_id);
CREATE INDEX IF NOT EXISTS ix_stg_reject_source_reason
    ON project_staging.stg_reject (source_system, reason_code);

CREATE TABLE IF NOT EXISTS project_staging.dq_result (
    dq_result_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id      BIGINT       NOT NULL,
    check_id        VARCHAR(16)  NOT NULL,
    check_name      VARCHAR(160) NOT NULL,
    severity        VARCHAR(12)  NOT NULL,
    table_name      VARCHAR(120),
    status          VARCHAR(8)   NOT NULL,
    observed_value  TEXT,
    expected_value  TEXT,
    details         TEXT,
    checked_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_dq_result_severity CHECK (severity IN ('CRITICAL', 'WARNING', 'INFO')),
    CONSTRAINT ck_dq_result_status CHECK (status IN ('PASS', 'FAIL', 'WARN', 'SKIP'))
);

CREATE INDEX IF NOT EXISTS ix_dq_result_run ON project_staging.dq_result (etl_run_id);
CREATE INDEX IF NOT EXISTS ix_dq_result_check ON project_staging.dq_result (check_id, status);
