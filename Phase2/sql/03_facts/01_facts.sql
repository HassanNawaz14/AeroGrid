-- Phase2/sql/00_schemas.sql so aerogrid_reader holds SELECT on project_dw tables.

CREATE SCHEMA IF NOT EXISTS project_dw;

CREATE TABLE IF NOT EXISTS project_dw.fact_vehicle_tracking (
    tracking_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_ts            TIMESTAMPTZ NOT NULL,
    time_key            BIGINT NOT NULL REFERENCES project_dw.dim_time(time_key),
    site_key            BIGINT NOT NULL REFERENCES project_dw.dim_site(site_key),
    vehicle_key         BIGINT NOT NULL REFERENCES project_dw.dim_vehicle(vehicle_key),
    grid_key            BIGINT NOT NULL REFERENCES project_dw.dim_spatial_grid(grid_key),
    weather_key         BIGINT NOT NULL REFERENCES project_dw.dim_weather(weather_key),
    altitude_msl_ft     NUMERIC(8,2),
    altitude_agl_ft     NUMERIC(8,2),
    altitude_source     VARCHAR(32),
    ground_speed_kts    NUMERIC(7,2),
    heading_deg         NUMERIC(6,2),
    vertical_rate_fps   NUMERIC(7,2),
    on_ground           BOOLEAN,
    source_quality_flag VARCHAR(32),
    source_system       VARCHAR(32) NOT NULL,
    source_record_id    VARCHAR(160) NOT NULL,
    source_file         TEXT,
    etl_run_id          BIGINT NOT NULL REFERENCES project_staging.etl_run_log(etl_run_id),
    loaded_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    algorithm_version   VARCHAR(32) NOT NULL,
    CONSTRAINT uq_fact_vehicle_tracking_source UNIQUE (source_system, source_record_id)
);

CREATE INDEX IF NOT EXISTS ix_fact_vehicle_tracking_event_ts
    ON project_dw.fact_vehicle_tracking (event_ts);
CREATE INDEX IF NOT EXISTS ix_fact_vehicle_tracking_site_event
    ON project_dw.fact_vehicle_tracking (site_key, event_ts);
CREATE INDEX IF NOT EXISTS ix_fact_vehicle_tracking_vehicle_event
    ON project_dw.fact_vehicle_tracking (vehicle_key, event_ts);
CREATE INDEX IF NOT EXISTS ix_fact_vehicle_tracking_time
    ON project_dw.fact_vehicle_tracking (time_key);
CREATE INDEX IF NOT EXISTS ix_fact_vehicle_tracking_grid
    ON project_dw.fact_vehicle_tracking (grid_key);
CREATE INDEX IF NOT EXISTS ix_fact_vehicle_tracking_weather
    ON project_dw.fact_vehicle_tracking (weather_key);
CREATE INDEX IF NOT EXISTS ix_fact_vehicle_tracking_etl_run
    ON project_dw.fact_vehicle_tracking (etl_run_id);

CREATE TABLE IF NOT EXISTS project_dw.fact_flight_journey (
    journey_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_key           BIGINT NOT NULL REFERENCES project_dw.dim_vehicle(vehicle_key),
    site_key              BIGINT NOT NULL REFERENCES project_dw.dim_site(site_key),
    start_ts              TIMESTAMPTZ NOT NULL,
    end_ts                TIMESTAMPTZ NOT NULL,
    start_time_key        BIGINT NOT NULL REFERENCES project_dw.dim_time(time_key),
    end_time_key          BIGINT NOT NULL REFERENCES project_dw.dim_time(time_key),
    origin_grid_key       BIGINT NOT NULL REFERENCES project_dw.dim_spatial_grid(grid_key),
    destination_grid_key  BIGINT NOT NULL REFERENCES project_dw.dim_spatial_grid(grid_key),
    flight_duration_sec   INTEGER NOT NULL CHECK (flight_duration_sec >= 0),
    max_altitude_ft       NUMERIC(8,2),
    total_distance_nm     NUMERIC(9,3) NOT NULL CHECK (total_distance_nm >= 0),
    avg_speed_kts         NUMERIC(7,2),
    journey_source        VARCHAR(16) NOT NULL,
    segment_reason        VARCHAR(64),
    source_system         VARCHAR(32) NOT NULL,
    source_record_id      VARCHAR(160) NOT NULL,
    etl_run_id            BIGINT NOT NULL REFERENCES project_staging.etl_run_log(etl_run_id),
    loaded_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    algorithm_version     VARCHAR(32) NOT NULL,
    CONSTRAINT ck_fact_flight_journey_window CHECK (end_ts >= start_ts),
    CONSTRAINT uq_fact_flight_journey_source UNIQUE (source_system, source_record_id)
);

CREATE INDEX IF NOT EXISTS ix_fact_flight_journey_start_ts
    ON project_dw.fact_flight_journey (start_ts);
CREATE INDEX IF NOT EXISTS ix_fact_flight_journey_end_ts
    ON project_dw.fact_flight_journey (end_ts);
CREATE INDEX IF NOT EXISTS ix_fact_flight_journey_site_start
    ON project_dw.fact_flight_journey (site_key, start_ts);
CREATE INDEX IF NOT EXISTS ix_fact_flight_journey_vehicle_start
    ON project_dw.fact_flight_journey (vehicle_key, start_ts);
CREATE INDEX IF NOT EXISTS ix_fact_flight_journey_start_time
    ON project_dw.fact_flight_journey (start_time_key);
CREATE INDEX IF NOT EXISTS ix_fact_flight_journey_end_time
    ON project_dw.fact_flight_journey (end_time_key);
CREATE INDEX IF NOT EXISTS ix_fact_flight_journey_etl_run
    ON project_dw.fact_flight_journey (etl_run_id);

