CREATE SCHEMA IF NOT EXISTS project_dw;

-- ---------------------------------------------------------------------------
-- fact_close_encounter
-- Grain: one detected conflict episode between two real vehicles at one site.
-- vehicle_key_1 < vehicle_key_2 gives a deterministic pair order and guarantees
-- the two vehicles are distinct (DQ-I-008, DQ-U-004).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_dw.fact_close_encounter (
    encounter_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_ts              TIMESTAMPTZ NOT NULL,
    end_ts                TIMESTAMPTZ NOT NULL,
    start_time_key        BIGINT NOT NULL REFERENCES project_dw.dim_time(time_key),
    site_key              BIGINT NOT NULL REFERENCES project_dw.dim_site(site_key),
    grid_key              BIGINT NOT NULL REFERENCES project_dw.dim_spatial_grid(grid_key),
    weather_key           BIGINT NOT NULL REFERENCES project_dw.dim_weather(weather_key),
    vehicle_key_1         BIGINT NOT NULL REFERENCES project_dw.dim_vehicle(vehicle_key),
    vehicle_key_2         BIGINT NOT NULL REFERENCES project_dw.dim_vehicle(vehicle_key),
    min_tracking_id_1     BIGINT REFERENCES project_dw.fact_vehicle_tracking(tracking_id),
    min_tracking_id_2     BIGINT REFERENCES project_dw.fact_vehicle_tracking(tracking_id),
    min_horizontal_sep_nm NUMERIC(7,3) NOT NULL,
    min_vertical_sep_ft   NUMERIC(8,2),
    conflict_duration_sec INTEGER NOT NULL,
    closing_speed_kts     NUMERIC(7,2),
    risk_severity_class   VARCHAR(16) NOT NULL,
    risk_severity_score   NUMERIC(7,3),
    algorithm_version     VARCHAR(32) NOT NULL,
    etl_run_id            BIGINT NOT NULL REFERENCES project_staging.etl_run_log(etl_run_id),
    loaded_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_fact_close_encounter_window CHECK (end_ts >= start_ts),
    CONSTRAINT ck_fact_close_encounter_pair_order CHECK (vehicle_key_1 < vehicle_key_2),
    CONSTRAINT ck_fact_close_encounter_horizontal CHECK (min_horizontal_sep_nm >= 0),
    CONSTRAINT ck_fact_close_encounter_vertical CHECK (min_vertical_sep_ft IS NULL OR min_vertical_sep_ft >= 0),
    CONSTRAINT ck_fact_close_encounter_duration CHECK (conflict_duration_sec >= 0),
    CONSTRAINT ck_fact_close_encounter_severity
        CHECK (risk_severity_class IN ('SEVERE', 'PROXIMITY', 'ADVISORY')),
    CONSTRAINT uq_fact_close_encounter_pair
        UNIQUE (vehicle_key_1, vehicle_key_2, start_ts, algorithm_version)
);

CREATE INDEX IF NOT EXISTS ix_fact_close_encounter_site_start
    ON project_dw.fact_close_encounter (site_key, start_ts);
CREATE INDEX IF NOT EXISTS ix_fact_close_encounter_start_time
    ON project_dw.fact_close_encounter (start_time_key);
CREATE INDEX IF NOT EXISTS ix_fact_close_encounter_grid
    ON project_dw.fact_close_encounter (grid_key);
CREATE INDEX IF NOT EXISTS ix_fact_close_encounter_weather
    ON project_dw.fact_close_encounter (weather_key);
CREATE INDEX IF NOT EXISTS ix_fact_close_encounter_vehicle_1
    ON project_dw.fact_close_encounter (vehicle_key_1);
CREATE INDEX IF NOT EXISTS ix_fact_close_encounter_vehicle_2
    ON project_dw.fact_close_encounter (vehicle_key_2);
CREATE INDEX IF NOT EXISTS ix_fact_close_encounter_etl_run
    ON project_dw.fact_close_encounter (etl_run_id);

-- ---------------------------------------------------------------------------
-- fact_restriction_activation
-- Grain: one evaluation of one airspace zone at one time interval.
-- Rows exist only where a real zone and real evidence (effective window or
-- snapshot) support them. Never insert synthetic evaluations.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_dw.fact_restriction_activation (
    activation_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_key               BIGINT NOT NULL REFERENCES project_dw.dim_time(time_key),
    evaluation_ts          TIMESTAMPTZ NOT NULL,
    site_key               BIGINT NOT NULL REFERENCES project_dw.dim_site(site_key),
    zone_key               BIGINT NOT NULL REFERENCES project_dw.dim_airspace_zone(zone_key),
    is_active              BOOLEAN NOT NULL,
    affected_traffic_count INTEGER,
    compliant_count        INTEGER,
    compliance_rate_pct    NUMERIC(6,2),
    source_system          VARCHAR(32) NOT NULL,
    source_record_id       VARCHAR(160),
    source_snapshot_ts     TIMESTAMPTZ,
    etl_run_id             BIGINT NOT NULL REFERENCES project_staging.etl_run_log(etl_run_id),
    loaded_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    algorithm_version      VARCHAR(32) NOT NULL,
    CONSTRAINT ck_fact_restriction_activation_counts
        CHECK (
            (affected_traffic_count IS NULL OR affected_traffic_count >= 0)
            AND (compliant_count IS NULL OR compliant_count >= 0)
            AND (
                affected_traffic_count IS NULL
                OR compliant_count IS NULL
                OR compliant_count <= affected_traffic_count
            )
        ),
    CONSTRAINT ck_fact_restriction_activation_rate
        CHECK (compliance_rate_pct IS NULL OR (compliance_rate_pct >= 0 AND compliance_rate_pct <= 100)),
    CONSTRAINT uq_fact_restriction_activation_zone_ts
        UNIQUE (zone_key, evaluation_ts, source_system)
);

CREATE INDEX IF NOT EXISTS ix_fact_restriction_activation_time
    ON project_dw.fact_restriction_activation (time_key);
CREATE INDEX IF NOT EXISTS ix_fact_restriction_activation_site
    ON project_dw.fact_restriction_activation (site_key);
CREATE INDEX IF NOT EXISTS ix_fact_restriction_activation_zone
    ON project_dw.fact_restriction_activation (zone_key);
CREATE INDEX IF NOT EXISTS ix_fact_restriction_activation_etl_run
    ON project_dw.fact_restriction_activation (etl_run_id);

-- ---------------------------------------------------------------------------
-- fact_airspace_occupancy
-- Grain: one hourly utilization snapshot per grid cell (dim_spatial_grid has no
-- altitude-band column, so the dictionary's uniqueness is per time_key + grid_key).
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_dw.fact_airspace_occupancy (
    occupancy_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_key                  BIGINT NOT NULL REFERENCES project_dw.dim_time(time_key),
    site_key                  BIGINT NOT NULL REFERENCES project_dw.dim_site(site_key),
    grid_key                  BIGINT NOT NULL REFERENCES project_dw.dim_spatial_grid(grid_key),
    active_vehicle_count      INTEGER NOT NULL,
    total_occupancy_minutes   NUMERIC(10,2) NOT NULL,
    avg_traffic_speed_kts     NUMERIC(7,2),
    supporting_tracking_count INTEGER NOT NULL,
    algorithm_version         VARCHAR(32) NOT NULL,
    etl_run_id                BIGINT NOT NULL REFERENCES project_staging.etl_run_log(etl_run_id),
    loaded_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_fact_airspace_occupancy_counts
        CHECK (active_vehicle_count >= 0 AND supporting_tracking_count >= active_vehicle_count),
    CONSTRAINT ck_fact_airspace_occupancy_minutes CHECK (total_occupancy_minutes >= 0),
    CONSTRAINT uq_fact_airspace_occupancy_cell_hour
        UNIQUE (time_key, grid_key, algorithm_version)
);

CREATE INDEX IF NOT EXISTS ix_fact_airspace_occupancy_site_time
    ON project_dw.fact_airspace_occupancy (site_key, time_key);
CREATE INDEX IF NOT EXISTS ix_fact_airspace_occupancy_grid
    ON project_dw.fact_airspace_occupancy (grid_key);
CREATE INDEX IF NOT EXISTS ix_fact_airspace_occupancy_etl_run
    ON project_dw.fact_airspace_occupancy (etl_run_id);
